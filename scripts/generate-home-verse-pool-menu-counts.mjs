#!/usr/bin/env node
/**
 * 从 explore-curated-700 与 theme-repeat-ge5 manifest 生成用户菜单池计数。
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const curatedManifestPath = path.join(
  repoRoot,
  "public",
  "data",
  "home-prayer-pools",
  "explore-curated-700",
  "manifest.json",
);
const ge5ManifestPath = path.join(
  repoRoot,
  "public",
  "data",
  "home-prayer-pools",
  "theme-repeat-ge5",
  "manifest.json",
);

function readManifest(filePath) {
  if (!fs.existsSync(filePath)) return null;
  const data = JSON.parse(fs.readFileSync(filePath, "utf8"));
  if (data?.version !== 1 || !Array.isArray(data.entries)) return null;
  return data;
}

function bookIdFromVerseKey(verseKey) {
  const m = /^([A-Z0-9]{3})\./.exec(String(verseKey ?? "").trim().toUpperCase());
  return m ? m[1] : null;
}

function isOldTestamentBookNumber(n) {
  return n >= 1 && n <= 39;
}

