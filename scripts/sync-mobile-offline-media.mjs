function emitGoldenVersePackRegistry(entries) {
  const imports = entries
    .map((e) => `  "${e.id}": require("../../../assets/audio/golden-verse-packs/${e.file}"),`)
    .join("\n");
  const revisions = entries
    .map((e) => {
      const abs = path.join(goldenVersePackDir, e.file);
      const size = fs.existsSync(abs) ? fs.statSync(abs).size : 0;
      return `  "${e.id}": "${size}",`;
    })
    .join("\n");
  const content = `// AUTO-GENERATED by scripts/sync-mobile-offline-media.mjs — do not edit
/** 金句朗读 zip（store-only）；运行时解压到 documentDirectory */
export const GOLDEN_VERSE_PACK_MODULES = {
${imports}
} as const;

/** zip 字节数，作已解压标记；免每次 Asset.loadAsync 百兆包 */
export const GOLDEN_VERSE_PACK_REVISIONS = {
${revisions}
} as const;
`;
  writeGeneratedTs("bundled-golden-verse-packs.ts", content);
}

function zipStoreDirectory(srcDirAbs, destZipAbs) {
  if (!fs.existsSync(srcDirAbs)) {
    console.warn(`  skip missing ${path.relative(repoRoot, srcDirAbs)}`);
    return false;
  }
  ensureDir(path.dirname(destZipAbs));
  if (fs.existsSync(destZipAbs)) fs.unlinkSync(destZipAbs);
  const parent = path.dirname(srcDirAbs);
  const base = path.basename(srcDirAbs);
  const result = spawnSync("zip", ["-0", "-r", "-q", destZipAbs, base], {
    cwd: parent,
    stdio: "inherit",
  });
  if (result.status !== 0) {
    console.warn(`  zip failed for ${base} (status=${result.status})`);
    if (fs.existsSync(destZipAbs)) fs.unlinkSync(destZipAbs);
    return false;
  }
  const mb = (fs.statSync(destZipAbs).size / (1024 * 1024)).toFixed(1);
  const count = fs.readdirSync(srcDirAbs).filter((n) => n.endsWith(".mp3")).length;
  console.log(
    `  ${base}/ (${count} mp3) → ${path.relative(repoRoot, destZipAbs)} (${mb} MB, zip -0)`,
  );
  return true;
}

function syncGoldenVerseAudioPacks(enabled) {
  rmDirIfExists(goldenVersePackDir);
  ensureDir(goldenVersePackDir);
  fs.writeFileSync(path.join(goldenVersePackDir, ".gitkeep"), "");
  const entries = [];
  if (!enabled) {
    emitGoldenVersePackRegistry(entries);
    console.log("Golden verse audio packs: skipped");
    return { packCount: 0 };
  }

  // 全量 zip 进安装包；首次点播再解。禁止写 Render ge5-delta。
  const deltaRoot = path.join(publicRoot, "audio", "golden-verse-ge5-delta");
  rmDirIfExists(deltaRoot);

  const stagingRoot = path.join(repoRoot, "tmp", "golden-verse-pack-staging");
  rmDirIfExists(stagingRoot);
  ensureDir(stagingRoot);

  console.log("Golden verse audio packs (full zip → install assets; first-play prepare):");
  const packs = [
    { id: "golden-verses", dir: path.join(publicRoot, "audio", "golden-verses") },
    {
      id: "golden-verses-web-en",
      dir: path.join(publicRoot, "audio", "golden-verses-web-en"),
    },
  ];

  for (const pack of packs) {
    if (!fs.existsSync(pack.dir)) {
      console.warn(`  skip missing ${path.relative(repoRoot, pack.dir)}`);
      continue;
    }
    const stagingDir = path.join(stagingRoot, pack.id);
    ensureDir(stagingDir);
    let count = 0;
    for (const name of fs.readdirSync(pack.dir)) {
      if (!name.endsWith(".mp3")) continue;
      fs.copyFileSync(path.join(pack.dir, name), path.join(stagingDir, name));
      count += 1;
    }
    const zipPath = path.join(goldenVersePackDir, `${pack.id}.zip`);
    if (count > 0 && zipStoreDirectory(stagingDir, zipPath)) {
      entries.push({ id: pack.id, file: `${pack.id}.zip` });
    }
    console.log(`  ${pack.id}: ${count} mp3 → assets`);
  }

  rmDirIfExists(stagingRoot);
  emitGoldenVersePackRegistry(entries);
  return { packCount: entries.length };
}

function emitResolver(fileName, exportFn, entries, requirePrefix, opts = {}) {
  const imports = entries
    .map((e) => `  "${e.id}": require("${requirePrefix}/${e.file}"),`)
    .join("\n");
  const moduleGetter = opts.moduleGetter
    ? `
export function get${opts.moduleGetter}(id: string): number | null {
  const mod = modules[id as keyof typeof modules];
  return mod ?? null;
}
`
    : "";
  const videoExtras = opts.videoExtras
    ? `${moduleGetter}
/** 安装包内场景：启动时解压到本地，切换时不再走网络 */
export async function preloadBundledNatureVideos(ids: readonly string[]): Promise<void> {
  const unique = [...new Set(ids.map((id) => id.trim()).filter(Boolean))];
  await Promise.all(
    unique.map(async (id) => {
      const mod = modules[id as keyof typeof modules];
      if (mod == null) return;
      const asset = Asset.fromModule(mod);
      if (asset.downloaded) return;
      await asset.downloadAsync();
    }),
  );
}
`
    : moduleGetter;
  const content = `// AUTO-GENERATED by scripts/sync-mobile-offline-media.mjs — do not edit
import { Asset } from "expo-asset";

const modules = {
${imports}
} as const;

export function ${exportFn}(id: string): string | null {
  const mod = modules[id as keyof typeof modules];
  if (mod == null) return null;
  return Asset.fromModule(mod).uri;
}
${videoExtras}`;
  writeGeneratedTs(fileName, content);
}

/** JSON 用 require 直接得到对象，不能走 Asset.fromModule（会闪退）。 */
function emitJsonMap(fileName, exportFn, entries, requirePrefix) {
  const imports = entries
    .map((e) => `  "${e.id}": require("${requirePrefix}/${e.file}"),`)
    .join("\n");
  const content = `// AUTO-GENERATED by scripts/sync-mobile-offline-media.mjs — do not edit

const data = {
${imports}
} as const;

export function ${exportFn}(id: string): (typeof data)[keyof typeof data] | null {
  const row = data[id as keyof typeof data];
  return row ?? null;
}
`;
  writeGeneratedTs(fileName, content);
}

function syncNature() {
  const settings = JSON.parse(fs.readFileSync(natureSettingsPath, "utf8"));
  const videos = Array.isArray(settings.videos) ? settings.videos : [];
  rmDirIfExists(natureVideoDir);
  rmDirIfExists(naturePosterDir);
  ensureDir(natureVideoDir);
  ensureDir(naturePosterDir);

  const videoEntries = [];
  const posterEntries = [];

  console.log("Nature videos & posters:");
  for (const v of videos) {
    const id = String(v.id || "").trim();
    if (!id) continue;
    const srcRel = resolveNatureVideoSrcForBundle(v.src);
    if (!srcRel) continue;
    const videoFile = `${id}.mp4`;
    if (copyIfExists(srcRel, path.join(natureVideoDir, videoFile))) {
      videoEntries.push({ id, file: videoFile });
    }
    const posterRel = String(v.previewFrameSrc || v.thumbSrc || "").trim();
    if (posterRel) {
      const ext = path.extname(posterRel) || ".jpg";
      const posterFile = `${id}${ext}`;
      if (copyIfExists(posterRel, path.join(naturePosterDir, posterFile))) {
        posterEntries.push({ id, file: posterFile });
      }
    }
  }

  emitResolver(
    "bundled-nature-videos.ts",
    "resolveBundledNatureVideoUri",
    videoEntries,
    "../../../assets/nature/videos",
    { videoExtras: true, moduleGetter: "BundledNatureVideoModule" },
  );
  emitResolver(
    "bundled-nature-posters.ts",
    "resolveBundledNaturePosterUri",
    posterEntries,
    "../../../assets/nature/posters",
    { moduleGetter: "BundledNaturePosterModule" },
  );
  bakeNatureSoftPosters();
  bakeNatureSquarePosters();
  return { videoCount: videoEntries.length, posterCount: posterEntries.length };
}

function albumKeyForTrack(track) {
  const tags = Array.isArray(track?.tags) ? track.tags : [];
  const album = String(tags[0] || "").trim();
  return album || "_";
}

/** companion 顺序下，每个专辑第一首进 base；其余进 PAD。 */
function splitTracksForAndroidPad(tracks) {
  const seenAlbum = new Set();
  const base = [];
  const pad = [];
  for (const t of tracks) {
    if (t?.hidden === true) continue;
    const id = String(t.id || "").trim();
    const srcRel = String(t.src || "").trim();
    if (!id || !srcRel) continue;
    const album = albumKeyForTrack(t);
    if (!seenAlbum.has(album)) {
      seenAlbum.add(album);
      base.push(t);
    } else {
      pad.push(t);
    }
  }
  return { base, pad };
}

