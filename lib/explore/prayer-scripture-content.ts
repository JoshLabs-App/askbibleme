type PrayerScenario = {
  title: string;
  titleTw: string;
  titleEn: string;
  refs: string[];
};

export function resolvePrayerScenarioTitle(scenario: PrayerScenario, locale: string): string {
  if (locale === "en") return scenario.titleEn;
  if (locale === "zh-TW") return scenario.titleTw;
  return scenario.title;
}

