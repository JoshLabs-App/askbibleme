/** @param {CatechismTopicSection[]} outline @param {number} total */
export function assertOutlineCoversQuestions(outline, total) {
  if (!outline.length) throw new Error("outline is empty");
  if (outline[0].startQ !== 1) {
    throw new Error(`outline must start at Q1, got Q${outline[0].startQ}`);
  }
  for (let i = 0; i < outline.length; i++) {
    const section = outline[i];
    if (section.startQ > section.endQ) {
      throw new Error(`${section.id}: startQ ${section.startQ} > endQ ${section.endQ}`);
    }
    if (i > 0 && section.startQ !== outline[i - 1].endQ + 1) {
      throw new Error(
        `${section.id}: gap after ${outline[i - 1].id} (expected Q${outline[i - 1].endQ + 1}, got Q${section.startQ})`,
      );
    }
  }
  if (outline[outline.length - 1].endQ !== total) {
    throw new Error(`outline ends at Q${outline[outline.length - 1].endQ}, expected Q${total}`);
  }
}
