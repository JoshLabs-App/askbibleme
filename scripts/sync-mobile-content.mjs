#!/usr/bin/env node
/**
 * 将网站真源内容复制到 Expo 资源目录（文案、首页金句、圣经目录、音乐曲库等）。
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const destDir = path.join(repoRoot, "apps", "askbible-mobile", "assets", "content");
const generatedDir = path.join(repoRoot, "apps", "askbible-mobile", "src", "read", "reading-plan", "generated");

function filterPublicMusicCompanionStore(raw) {
  const audioTracks = (Array.isArray(raw.audioTracks) ? raw.audioTracks : []).filter(
    (t) => t && t.hidden !== true,
  );
  const visibleIds = new Set(audioTracks.map((t) => String(t.id || "").trim()).filter(Boolean));
  const scenes = (Array.isArray(raw.scenes) ? raw.scenes : []).map((scene) => ({
    ...scene,
    audioTrackId:
      scene.audioTrackId && visibleIds.has(scene.audioTrackId) ? scene.audioTrackId : null,
  }));
  return { ...raw, audioTracks, scenes };
}

const imageCopies = [
  ["public/read/parchment-scroll-bg.jpg", "read-parchment-scroll-bg.jpg"],
  ["public/read/parchment-scroll-bg-wide.jpg", "read-parchment-scroll-bg-wide.jpg"],
  ["public/read/post-reading/discover-self.png", "post-reading/discover-self.png"],
  ["public/read/post-reading/consult-materials.png", "post-reading/consult-materials.png"],
];

const copies = [
  ["locales/zh-CN.json", "zh-CN.json"],
  ["locales/en.json", "en.json"],
  ["lib/oauth-brand-icon-paths.ts", "../../src/auth/oauth-brand-icon-paths.ts"],
  ["data/bible/scripture_canon_catalog.json", "scripture_canon_catalog.json"],
  ["data/bible/bible_book_history_eras.json", "bible_book_history_eras.json"],
  ["data/music-companion.json", "music-companion.json"],
  ["data/nature-settings.json", "nature-settings.json"],
  ["data/bible/info-edition-v1-published.json", "info-edition-v1-published.json"],
  ["data/admin/generation-roles.json", "generation-roles.json"],
  ["data/bible-reading-plans/registry.json", "reading-plans-registry.json"],
  ["data/bible/teochew-nt-audio-manifest.json", "../bible/teochew-nt-audio-manifest.json"],
];

fs.mkdirSync(destDir, { recursive: true });

for (const [relSrc, destName] of copies) {
  const src = path.join(repoRoot, relSrc);
  const dest = path.join(destDir, destName);
  if (!fs.existsSync(src)) {
    console.error(`Missing ${src}`);
    process.exit(1);
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  if (relSrc === "data/music-companion.json") {
    const raw = JSON.parse(fs.readFileSync(src, "utf8"));
    fs.writeFileSync(dest, `${JSON.stringify(filterPublicMusicCompanionStore(raw), null, 2)}\n`);
  } else {
    fs.copyFileSync(src, dest);
  }
  const kb = (fs.statSync(dest).size / 1024).toFixed(1);
  console.log(`Copied ${relSrc} (${kb} KB) → apps/askbible-mobile/assets/content/${destName}`);
}

const imagesDir = path.join(repoRoot, "apps", "askbible-mobile", "assets", "images");
fs.mkdirSync(imagesDir, { recursive: true });
for (const [relSrc, destRel] of imageCopies) {
  const src = path.join(repoRoot, relSrc);
  const dest = path.join(imagesDir, destRel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  if (!fs.existsSync(src)) {
    console.error(`Missing ${src}`);
    process.exit(1);
  }
  fs.copyFileSync(src, dest);
  const kb = (fs.statSync(dest).size / 1024).toFixed(1);
  console.log(`Copied ${relSrc} (${kb} KB) → apps/askbible-mobile/assets/images/${destRel}`);
}

const plansSrcDir = path.join(repoRoot, "data", "bible-reading-plans", "built");
const plansDestDir = path.join(destDir, "reading-plans");
const registryPath = path.join(destDir, "reading-plans-registry.json");

if (!fs.existsSync(registryPath)) {
  console.error(`Missing ${registryPath} (registry copy failed)`);
  process.exit(1);
}

const registry = JSON.parse(fs.readFileSync(registryPath, "utf8"));
const planEntries = Array.isArray(registry.plans) ? registry.plans : [];

fs.mkdirSync(plansDestDir, { recursive: true });
/** @type {{ planId: string, file: string }[]} */
const bundledPlans = [];

console.log("Reading plan bundles:");
for (const plan of planEntries) {
  const planId = String(plan.planId || "").trim();
  const bundlePath = String(plan.bundlePath || "").trim();
  if (!planId || !bundlePath) continue;
  const src = path.join(repoRoot, bundlePath);
  if (!fs.existsSync(src)) {
    console.warn(`  skip missing plan bundle ${bundlePath}`);
    continue;
  }
  const file = `${planId}.json`;
  fs.copyFileSync(src, path.join(plansDestDir, file));
  bundledPlans.push({ planId, file });
  const kb = (fs.statSync(src).size / 1024).toFixed(1);
  console.log(`  ${planId} (${kb} KB)`);
}

fs.mkdirSync(generatedDir, { recursive: true });
const requireLines = bundledPlans
  .map((p) => `  "${p.planId}": require("../../../../assets/content/reading-plans/${p.file}"),`)
  .join("\n");

const generatedTs = `// AUTO-GENERATED by scripts/sync-mobile-content.mjs — do not edit
import type { ReadingPlanRegistry } from "../types";

// eslint-disable-next-line @typescript-eslint/no-require-imports
export const BUNDLED_READING_PLAN_REGISTRY = require("../../../../assets/content/reading-plans-registry.json") as ReadingPlanRegistry;

const planBundles = {
${requireLines}
} as const;

export type BundledReadingPlanBundle = {
  schemaVersion: 1;
  planId: string;
  name: string;
  abbreviation?: string;
  description?: string;
  days: import("../types").ReadingPlanDay[];
};

export function getBundledReadingPlanBundle(planId: string): BundledReadingPlanBundle | null {
  const id = planId.trim();
  if (!id) return null;
  const raw = planBundles[id as keyof typeof planBundles];
  if (!raw || typeof raw !== "object") return null;
  return raw as BundledReadingPlanBundle;
}
`;

fs.writeFileSync(path.join(generatedDir, "bundled-reading-plans.ts"), generatedTs);
console.log(`Wrote ${path.relative(repoRoot, path.join(generatedDir, "bundled-reading-plans.ts"))} (${bundledPlans.length} plans)`);

const exploreSync = spawnSync("node", ["scripts/sync-explore-featured-articles-localized.mjs"], {
  cwd: repoRoot,
  stdio: "inherit",
});
if (exploreSync.status !== 0) process.exit(exploreSync.status ?? 1);

const figuresSync = spawnSync("npx", ["tsx", "scripts/sync-legacy-figures-bundles.ts"], {
  cwd: repoRoot,
  stdio: "inherit",
});
if (figuresSync.status !== 0) process.exit(figuresSync.status ?? 1);

const exploreModulesSync = spawnSync("npx", ["tsx", "scripts/sync-explore-modules-bundles.ts"], {
  cwd: repoRoot,
  stdio: "inherit",
});
if (exploreModulesSync.status !== 0) process.exit(exploreModulesSync.status ?? 1);

const wideParchmentSrc = path.join(repoRoot, "public/read/parchment-scroll-bg-wide.jpg");
const widgetAssetPaths = [
  path.join(
    repoRoot,
    "apps/askbible-mobile/android/app/src/main/res/drawable-nodpi/widget_parchment_scroll_bg.jpg",
  ),
  path.join(
    repoRoot,
    "apps/askbible-mobile/targets/widget/Assets.xcassets/WidgetParchmentBg.imageset/WidgetParchmentBg.jpg",
  ),
];
if (fs.existsSync(wideParchmentSrc)) {
  for (const dest of widgetAssetPaths) {
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(wideParchmentSrc, dest);
  }
  console.log("Synced parchment-scroll-bg-wide.jpg → widget Android/iOS assets");
}
