#!/usr/bin/env node
/**
 * Bake soft (pre-blurred) nature posters from sharp posters.
 * Matches home 「微」柔焦观感，供默认静帧省电路径使用（无运行时 BlurView / blurRadius）。
 *
 * Usage: node scripts/bake-nature-soft-posters.mjs
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sharpDir = path.join(repoRoot, "apps/askbible-mobile/assets/nature/posters");
const softDir = path.join(repoRoot, "apps/askbible-mobile/assets/nature/posters-soft");
const generatedDir = path.join(
  repoRoot,
  "apps/askbible-mobile/src/media/generated",
);

/** 接近当前 App「微」档：轻柔焦，仍能辨认场景 */
const GBLUR_SIGMA = 6;

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function writeGenerated(entries) {
  const imports = entries
    .map((e) => `  "${e.id}": require("../../../assets/nature/posters-soft/${e.file}"),`)
    .join("\n");
  const content = `// AUTO-GENERATED by scripts/bake-nature-soft-posters.mjs — do not edit
import { Asset } from "expo-asset";

const modules = {
${imports}
} as const;

export function resolveBundledNatureSoftPosterUri(id: string): string | null {
  const mod = modules[id as keyof typeof modules];
  if (mod == null) return null;
  return Asset.fromModule(mod).uri;
}

export function getBundledNatureSoftPosterModule(id: string): number | null {
  const mod = modules[id as keyof typeof modules];
  return mod ?? null;
}
`;
  ensureDir(generatedDir);
  fs.writeFileSync(path.join(generatedDir, "bundled-nature-posters-soft.ts"), content);
}

function main() {
  if (!fs.existsSync(sharpDir)) {
    console.error(`Missing sharp posters: ${sharpDir}`);
    process.exit(1);
  }
  ensureDir(softDir);

  const files = fs
    .readdirSync(sharpDir)
    .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
    .sort();
  if (!files.length) {
    console.error("No poster files to bake.");
    process.exit(1);
  }

  const entries = [];
  console.log(`Baking ${files.length} soft poster(s) (gblur sigma=${GBLUR_SIGMA})…`);
  for (const file of files) {
    const id = path.basename(file, path.extname(file));
    const src = path.join(sharpDir, file);
    const outName = `${id}.jpg`;
    const out = path.join(softDir, outName);
    execFileSync(
      "ffmpeg",
      [
        "-y",
        "-i",
        src,
        "-vf",
        `gblur=sigma=${GBLUR_SIGMA}`,
        "-q:v",
        "3",
        out,
      ],
      { stdio: "pipe" },
    );
    const sizeKb = Math.round(fs.statSync(out).size / 1024);
    console.log(`  ✓ ${outName} (${sizeKb} KB)`);
    entries.push({ id, file: outName });
  }

  writeGenerated(entries);
  console.log(`Wrote bundled-nature-posters-soft.ts (${entries.length} entries)`);
}

main();
