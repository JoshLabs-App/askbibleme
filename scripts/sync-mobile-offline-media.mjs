#!/usr/bin/env node
/**
 * 将自然场景 720p、海报、音乐 starter 曲与分析 JSON 复制进 Expo assets，并生成 require 注册表。
 * - 默认：仅打包 1 首 starter 音乐（MOBILE_STARTER_MUSIC_TRACK_ID，默认 Silent Prayer）
 * - MOBILE_BUNDLE_OFFLINE_MEDIA=1：打包自然场景；MOBILE_BUNDLE_MUSIC_LIMIT 控制音乐曲数（生产建议 1）
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicRoot = path.join(repoRoot, "public");
const generatedDir = path.join(repoRoot, "apps", "askbible-mobile", "src", "media", "generated");

const natureSettingsPath = path.join(repoRoot, "data", "nature-settings.json");
const musicPath = path.join(repoRoot, "data", "music-companion.json");

const natureVideoDir = path.join(repoRoot, "apps", "askbible-mobile", "assets", "nature", "videos");
const naturePosterDir = path.join(repoRoot, "apps", "askbible-mobile", "assets", "nature", "posters");
const musicTrackDir = path.join(repoRoot, "apps", "askbible-mobile", "assets", "music", "tracks");
const musicAnalysisDir = path.join(repoRoot, "apps", "askbible-mobile", "assets", "music", "analysis");
const bundleEnabled = process.env.MOBILE_BUNDLE_OFFLINE_MEDIA === "1";
const starterTrackId = String(process.env.MOBILE_STARTER_MUSIC_TRACK_ID || "track-mpg4a7xcip5q").trim();
const bundleMusicLimitRaw = process.env.MOBILE_BUNDLE_MUSIC_LIMIT?.trim();
const bundleMusicLimit = bundleMusicLimitRaw
  ? Math.max(1, Number(bundleMusicLimitRaw) || 1)
  : bundleEnabled
    ? Number.POSITIVE_INFINITY
    : 1;

function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}

function copyIfExists(srcRel, destAbs) {
  const src = path.join(publicRoot, srcRel.replace(/^\//, ""));
  if (!fs.existsSync(src)) {
    console.warn(`  skip missing ${srcRel}`);
    return false;
  }
  ensureDir(path.dirname(destAbs));
  fs.copyFileSync(src, destAbs);
  const mb = (fs.statSync(destAbs).size / (1024 * 1024)).toFixed(2);
  console.log(`  ${srcRel} → ${path.relative(repoRoot, destAbs)} (${mb} MB)`);
  return true;
}

/**
 * 自然场景优先打包 1080p：若 settings 指向 720，则尝试同前缀的 -1080 文件。
 * 仅在文件存在时替换，避免破坏现有兼容性。
 */
function resolveNatureVideoSrcForBundle(srcRel) {
  const trimmed = String(srcRel || "").trim();
  if (!trimmed) return trimmed;
  if (!trimmed.endsWith("-720.mp4")) return trimmed;
  const preferred1080 = trimmed.replace(/-720\.mp4$/i, "-1080.mp4");
  const preferredAbs = path.join(publicRoot, preferred1080.replace(/^\//, ""));
  if (fs.existsSync(preferredAbs)) return preferred1080;
  return trimmed;
}

function writeGeneratedTs(filename, body) {
  ensureDir(generatedDir);
  const out = path.join(generatedDir, filename);
  fs.writeFileSync(out, body);
  console.log(`Wrote ${path.relative(repoRoot, out)}`);
}

function rmDirIfExists(dir) {
  if (fs.existsSync(dir)) fs.rmSync(dir, { recursive: true, force: true });
}

function clearBundledOfflineMediaFiles() {
  rmDirIfExists(natureVideoDir);
  rmDirIfExists(naturePosterDir);
  rmDirIfExists(musicTrackDir);
  rmDirIfExists(musicAnalysisDir);
}

function emitResolver(fileName, exportFn, entries, requirePrefix, opts = {}) {
  const imports = entries
    .map((e) => `  "${e.id}": require("${requirePrefix}/${e.file}"),`)
    .join("\n");
  const moduleGetter = opts.moduleGetter
    ? `
export function get${opts.moduleGetter}(id: string): number | null {
  const mod = modules[id as keyof typeof modules];
  return mod ?? null;
}
`
    : "";
  const videoExtras = opts.videoExtras
    ? `${moduleGetter}
/** 安装包内场景：启动时解压到本地，切换时不再走网络 */
export async function preloadBundledNatureVideos(ids: readonly string[]): Promise<void> {
  const unique = [...new Set(ids.map((id) => id.trim()).filter(Boolean))];
  await Promise.all(
    unique.map(async (id) => {
      const mod = modules[id as keyof typeof modules];
      if (mod == null) return;
      const asset = Asset.fromModule(mod);
      if (asset.downloaded) return;
      await asset.downloadAsync();
    }),
  );
}
`
    : moduleGetter;
  const content = `// AUTO-GENERATED by scripts/sync-mobile-offline-media.mjs — do not edit
import { Asset } from "expo-asset";

const modules = {
${imports}
} as const;

export function ${exportFn}(id: string): string | null {
  const mod = modules[id as keyof typeof modules];
  if (mod == null) return null;
  return Asset.fromModule(mod).uri;
}
${videoExtras}`;
  writeGeneratedTs(fileName, content);
}

/** JSON 用 require 直接得到对象，不能走 Asset.fromModule（会闪退）。 */
function emitJsonMap(fileName, exportFn, entries, requirePrefix) {
  const imports = entries
    .map((e) => `  "${e.id}": require("${requirePrefix}/${e.file}"),`)
    .join("\n");
  const content = `// AUTO-GENERATED by scripts/sync-mobile-offline-media.mjs — do not edit

const data = {
${imports}
} as const;

export function ${exportFn}(id: string): (typeof data)[keyof typeof data] | null {
  const row = data[id as keyof typeof data];
  return row ?? null;
}
`;
  writeGeneratedTs(fileName, content);
}

function syncNature() {
  const settings = JSON.parse(fs.readFileSync(natureSettingsPath, "utf8"));
  const videos = Array.isArray(settings.videos) ? settings.videos : [];
  rmDirIfExists(natureVideoDir);
  rmDirIfExists(naturePosterDir);
  ensureDir(natureVideoDir);
  ensureDir(naturePosterDir);

  const videoEntries = [];
  const posterEntries = [];

  console.log("Nature videos & posters:");
  for (const v of videos) {
    const id = String(v.id || "").trim();
    if (!id) continue;
    const srcRel = resolveNatureVideoSrcForBundle(v.src);
    if (!srcRel) continue;
    const videoFile = `${id}.mp4`;
    if (copyIfExists(srcRel, path.join(natureVideoDir, videoFile))) {
      videoEntries.push({ id, file: videoFile });
    }
    const posterRel = String(v.previewFrameSrc || v.thumbSrc || "").trim();
    if (posterRel) {
      const ext = path.extname(posterRel) || ".jpg";
      const posterFile = `${id}${ext}`;
      if (copyIfExists(posterRel, path.join(naturePosterDir, posterFile))) {
        posterEntries.push({ id, file: posterFile });
      }
    }
  }

  emitResolver(
    "bundled-nature-videos.ts",
    "resolveBundledNatureVideoUri",
    videoEntries,
    "../../../assets/nature/videos",
    { videoExtras: true, moduleGetter: "BundledNatureVideoModule" },
  );
  emitResolver(
    "bundled-nature-posters.ts",
    "resolveBundledNaturePosterUri",
    posterEntries,
    "../../../assets/nature/posters",
    { moduleGetter: "BundledNaturePosterModule" },
  );
  return { videoCount: videoEntries.length, posterCount: posterEntries.length };
}

function syncMusic() {
  const store = JSON.parse(fs.readFileSync(musicPath, "utf8"));
  const tracks = Array.isArray(store.audioTracks) ? store.audioTracks : [];
  rmDirIfExists(musicTrackDir);
  rmDirIfExists(musicAnalysisDir);
  ensureDir(musicTrackDir);
  ensureDir(musicAnalysisDir);

  const trackEntries = [];
  const analysisEntries = [];
  const orderedTracks = [...tracks];
  if (starterTrackId) {
    orderedTracks.sort((a, b) => {
      const aHit = String(a.id || "").trim() === starterTrackId ? 0 : 1;
      const bHit = String(b.id || "").trim() === starterTrackId ? 0 : 1;
      return aHit - bHit;
    });
  }

  console.log(
    bundleMusicLimit === Number.POSITIVE_INFINITY
      ? "Music tracks:"
      : `Music tracks (bundle limit=${bundleMusicLimit}, starter=${starterTrackId || "first"}):`,
  );
  for (const t of orderedTracks) {
    if (trackEntries.length >= bundleMusicLimit) break;
    const id = String(t.id || "").trim();
    const srcRel = String(t.src || "").trim();
    if (!id || !srcRel) continue;
    if (starterTrackId && trackEntries.length === 0 && bundleMusicLimit === 1 && id !== starterTrackId) {
      continue;
    }
    const ext = path.extname(srcRel) || ".m4a";
    const trackFile = `${id}${ext}`;
    if (copyIfExists(srcRel, path.join(musicTrackDir, trackFile))) {
      trackEntries.push({ id, file: trackFile });
    }
    const analysisRel = String(t.analysisSrc || "").trim();
    if (analysisRel) {
      const aExt = path.extname(analysisRel) || ".json";
      const analysisFile = `${id}${aExt}`;
      if (copyIfExists(analysisRel, path.join(musicAnalysisDir, analysisFile))) {
        analysisEntries.push({ id, file: analysisFile });
      }
    }
  }

  emitResolver(
    "bundled-music-tracks.ts",
    "resolveBundledMusicTrackUri",
    trackEntries,
    "../../../assets/music/tracks",
    { moduleGetter: "BundledMusicTrackModule" },
  );
  emitJsonMap(
    "bundled-music-analysis.ts",
    "getBundledMusicAnalysis",
    analysisEntries,
    "../../../assets/music/analysis",
  );
  return { trackCount: trackEntries.length, analysisCount: analysisEntries.length };
}

if (!bundleEnabled) {
  clearBundledOfflineMediaFiles();
  emitResolver(
    "bundled-nature-videos.ts",
    "resolveBundledNatureVideoUri",
    [],
    "../../../assets/nature/videos",
    { videoExtras: true, moduleGetter: "BundledNatureVideoModule" },
  );
  emitResolver(
    "bundled-nature-posters.ts",
    "resolveBundledNaturePosterUri",
    [],
    "../../../assets/nature/posters",
    { moduleGetter: "BundledNaturePosterModule" },
  );
  const music = syncMusic();
  console.log(
    `Offline media: nature streamed/downloaded at runtime; bundled starter music=${music.trackCount} track(s).`,
  );
  console.log(
    "Set MOBILE_BUNDLE_OFFLINE_MEDIA=1 to bundle nature + more music for fully offline APK.",
  );
  process.exit(0);
}

const nature = syncNature();
const music = syncMusic();
console.log(
  `\nOffline media ready: ${nature.videoCount} videos, ${nature.posterCount} posters, ${music.trackCount} tracks.`,
);
