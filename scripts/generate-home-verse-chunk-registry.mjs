#!/usr/bin/env node
/**
 * 为 Web / Metro 生成 home-prayer-pool chunk require 注册表。
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const scopeId = process.env.HOME_PRAYER_POOL_SCOPE_ID?.trim() || "theme-repeat-ge5";

const publicPoolDir = path.join(repoRoot, "public", "data", "home-prayer-pools", scopeId);
const mobilePoolDir = path.join(
  repoRoot,
  "apps",
  "askbible-mobile",
  "assets",
  "content",
  "home-prayer-pools",
  scopeId,
);

function readChunkIndices(poolDir) {
  if (!fs.existsSync(path.join(poolDir, "manifest.json"))) {
    console.error(`Missing ${poolDir}/manifest.json. Run: npm run build:curated-700-pool`);
    process.exit(1);
  }
  return fs
    .readdirSync(poolDir)
    .filter((n) => /^chunk-\d+\.json$/.test(n))
    .map((n) => Number(n.replace("chunk-", "").replace(".json", "")))
    .sort((a, b) => a - b);
}

function writeWebRegistry(chunkFiles) {
  const outFile = path.join(repoRoot, "lib", "home-prayer-pools", "chunk-registry.generated.ts");
  const relPrefix = `../../public/data/home-prayer-pools/${scopeId}`;
  const lines = [
    "/** AUTO-GENERATED by scripts/generate-home-verse-chunk-registry.mjs — do not edit */",
    'import type { HomePrayerChunkV1, HomePrayerManifestV1 } from "@/lib/home-prayer-pools/types";',
    "",
    `export const HOME_PRAYER_POOL_MANIFEST = require("${relPrefix}/manifest.json") as HomePrayerManifestV1;`,
    "",
    `export const HOME_PRAYER_POOL_SCOPE_ID = "${scopeId}" as const;`,
    "",
    "export const HOME_PRAYER_POOL_CHUNKS: Record<number, HomePrayerChunkV1> = {",
  ];
  for (const i of chunkFiles) {
    lines.push(`  ${i}: require("${relPrefix}/chunk-${i}.json") as HomePrayerChunkV1,`);
  }
  lines.push("};", "");
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, `${lines.join("\n")}\n`);
  console.log(`Wrote ${outFile} (${chunkFiles.length} chunks)`);
}

function writeMobileRegistry(chunkFiles) {
  const outFile = path.join(
    repoRoot,
    "apps",
    "askbible-mobile",
    "src",
    "home",
    "verse-pool",
    "chunk-registry.generated.ts",
  );
  const relPrefix = `../../../assets/content/home-prayer-pools/${scopeId}`;
  const lines = [
    "/** AUTO-GENERATED by scripts/generate-home-verse-chunk-registry.mjs — do not edit */",
    'import type { HomePrayerChunkV1 } from "./types";',
    "",
    `export const HOME_VERSE_POOL_SCOPE_ID = "${scopeId}" as const;`,
    "",
    "/** 按需 require：全量 ge5 有 200+ chunk，启动时不可全部同步加载。 */",
    "const HOME_VERSE_POOL_CHUNK_LOADERS: Record<number, () => HomePrayerChunkV1> = {",
  ];
  for (const i of chunkFiles) {
    lines.push(`  ${i}: () => require("${relPrefix}/chunk-${i}.json") as HomePrayerChunkV1,`);
  }
  lines.push("};", "");
  lines.push("export function getHomeVersePoolChunk(index: number): HomePrayerChunkV1 | null {");
  lines.push("  const load = HOME_VERSE_POOL_CHUNK_LOADERS[index];");
  lines.push("  if (!load) return null;");
  lines.push("  try {");
  lines.push("    return load();");
  lines.push("  } catch {");
  lines.push("    return null;");
  lines.push("  }");
  lines.push("}", "");
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, `${lines.join("\n")}\n`);
  console.log(`Wrote ${outFile} (${chunkFiles.length} lazy chunks)`);
}

const chunkFiles = readChunkIndices(publicPoolDir);
writeWebRegistry(chunkFiles);
if (fs.existsSync(mobilePoolDir)) {
  writeMobileRegistry(chunkFiles);
} else {
  console.warn(`Skip mobile registry: ${mobilePoolDir} not found (run mobile:sync-home-verse-pool)`);
}
