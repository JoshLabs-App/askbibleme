const curated = readManifest(curatedManifestPath);
const ge5 = readManifest(ge5ManifestPath);

const counts = {
  curated700: curated?.entries?.length ?? 700,
  repeatGe5All: ge5?.entries?.length ?? 0,
  repeatGe5Old: 0,
  repeatGe5New: 0,
  books: {},
};

if (ge5?.entries?.length) {
  for (const entry of ge5.entries) {
    const bookId = bookIdFromVerseKey(entry.verseKey);
    if (!bookId) continue;
    counts.books[bookId] = (counts.books[bookId] ?? 0) + 1;
    const n = bookNumbers[bookId] ?? 0;
    if (isOldTestamentBookNumber(n)) counts.repeatGe5Old += 1;
    else counts.repeatGe5New += 1;
  }
}

const outFile = path.join(repoRoot, "lib", "home-prayer-pools", "home-verse-pool-menu-counts.generated.ts");
const lines = [
  "/** AUTO-GENERATED by scripts/generate-home-verse-pool-menu-counts.mjs — do not edit */",
  "",
  "export type HomeVersePoolMenuCounts = {",
  "  curated700: number;",
  "  repeatGe5All: number;",
  "  repeatGe5Old: number;",
  "  repeatGe5New: number;",
  "  books: Record<string, number>;",
  "};",
  "",
  "export const HOME_VERSE_POOL_MENU_COUNTS: HomeVersePoolMenuCounts = ",
  JSON.stringify(counts, null, 2),
  ";",
  "",
];
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `${lines.join("\n")}\n`);
console.log(
  `Wrote ${outFile} (curated700=${counts.curated700}, ge5=${counts.repeatGe5All}, OT=${counts.repeatGe5Old}, NT=${counts.repeatGe5New})`,
);
