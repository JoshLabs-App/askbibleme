function nextDateNumberedLabel(
  prefix: string,
  existingTitles: readonly string[],
  now: Date,
): string {
  const ymd = localYmd(now);
  const escaped = prefix.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const re = new RegExp(`^${escaped} ${ymd.replace(/-/g, "\\-")} · (\\d{2})$`);
  let max = 0;
  for (const raw of existingTitles) {
    const t = (raw ?? "").trim();
    const m = t.match(re);
    if (m) max = Math.max(max, parseInt(m[1], 10));
  }
  const next = Math.min(99, max + 1);
  return `${prefix} ${ymd} · ${pad2(next)}`.slice(0, MAX_TITLE_LEN);
}

/** 上传自动生成的音乐标题（播放页不展示，避免机器感） */
const AUTO_MUSIC_TITLE_PATTERNS = [
  /^音乐 \d{4}-\d{2}-\d{2} · \d{2}$/,
  /^安静敬拜 · \d{2}$/,
];

export function isAutoGeneratedMusicTrackTitle(title: string): boolean {
  const normalized = title.trim();
  return AUTO_MUSIC_TITLE_PATTERNS.some((re) => re.test(normalized));
}

