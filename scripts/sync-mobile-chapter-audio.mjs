#!/usr/bin/env node
/**
 * 章朗读 mp3：默认不复制进安装包（省 ~1GB）；联网时走 FHL(version=20) / 自托管 URL。
 * 需要打进 APK 时：MOBILE_BUNDLE_CHAPTER_AUDIO=1 npm run mobile:sync-chapter-audio
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicAudio = path.join(repoRoot, "public", "audio");
const destRoot = path.join(repoRoot, "apps", "askbible-mobile", "assets", "audio");
const generatedPath = path.join(
  repoRoot,
  "apps",
  "askbible-mobile",
  "src",
  "media",
  "generated",
  "bundled-chapter-audio.ts",
);

const bundleEnabled = process.env.MOBILE_BUNDLE_CHAPTER_AUDIO === "1";

/** @type {{ key: string, relRequire: string }[]} */
const entries = [];

function rmDirIfExists(dir) {
  if (fs.existsSync(dir)) fs.rmSync(dir, { recursive: true, force: true });
}

function clearBundledChapterAudioFiles() {
  fs.mkdirSync(destRoot, { recursive: true });
  rmDirIfExists(path.join(destRoot, "web-en"));
  rmDirIfExists(path.join(destRoot, "blm-es"));
  rmDirIfExists(path.join(destRoot, "cuv-v20"));
  rmDirIfExists(path.join(destRoot, "teochew-nt"));
  for (const name of fs.readdirSync(destRoot)) {
    if (!name.endsWith(".mp3")) continue;
    if (name === "today-plan-complete.mp3") continue;
    fs.unlinkSync(path.join(destRoot, name));
  }
}

function writeGeneratedRegistry() {
  const lines = entries
    .map((e) => `  "${e.key}": require("${e.relRequire}"),`)
    .join("\n");

  const body = `// AUTO-GENERATED by scripts/sync-mobile-chapter-audio.mjs — do not edit
/** 章朗读 mp3；无文件时为空对象 */
export const CHAPTER_AUDIO_MODULES = {
${lines}
} as const;
`;

  fs.mkdirSync(path.dirname(generatedPath), { recursive: true });
  fs.writeFileSync(generatedPath, body);
}

function copyMp3(key, srcAbs, destRel) {
  const destAbs = path.join(destRoot, destRel);
  fs.mkdirSync(path.dirname(destAbs), { recursive: true });
  fs.copyFileSync(srcAbs, destAbs);
  entries.push({ key, relRequire: `../../../assets/audio/${destRel.replace(/\\/g, "/")}` });
}

function walkFlat(scopePrefix, subdir) {
  const dir = path.join(publicAudio, subdir);
  if (!fs.existsSync(dir)) return;
  for (const name of fs.readdirSync(dir)) {
    if (!name.endsWith(".mp3")) continue;
    const base = name.slice(0, -4);
    copyMp3(`${scopePrefix}:${base}`, path.join(dir, name), path.join(subdir, name));
  }
}

clearBundledChapterAudioFiles();

if (!bundleEnabled) {
  writeGeneratedRegistry();
  console.log(
    "Chapter audio: skipped APK bundle (default). Stream at runtime; set MOBILE_BUNDLE_CHAPTER_AUDIO=1 to bundle.",
  );
  process.exit(0);
}

if (fs.existsSync(publicAudio)) {
  for (const name of fs.readdirSync(publicAudio)) {
    const full = path.join(publicAudio, name);
    if (name.endsWith(".mp3") && fs.statSync(full).isFile()) {
      copyMp3(`cuv:${name.slice(0, -4)}`, full, name);
      continue;
    }
    if (!fs.statSync(full).isDirectory()) continue;
    if (name === "web-en") {
      walkFlat("web-en", "web-en");
    } else if (name === "blm-es") {
      walkFlat("blm-es", "blm-es");
    } else if (name === "cuv-v20") {
      walkFlat("cuv-v20", "cuv-v20");
    } else if (name === "teochew-nt") {
      walkFlat("teochew-nt", "teochew-nt");
    }
  }
}

writeGeneratedRegistry();
console.log(
  entries.length > 0
    ? `Bundled ${entries.length} chapter audio file(s) → apps/askbible-mobile/assets/audio/`
    : "No public/audio/*.mp3 found — wrote empty CHAPTER_AUDIO_MODULES.",
);
