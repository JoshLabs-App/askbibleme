#!/usr/bin/env node
/**
 * 为 Metro 生成 chunk require 注册表（动态路径无法 require）。
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const poolDir = path.join(
  repoRoot,
  "apps",
  "askbible-mobile",
  "assets",
  "content",
  "home-prayer-pools",
  "theme-repeat-ge5",
);
const outFile = path.join(
  repoRoot,
  "apps",
  "askbible-mobile",
  "src",
  "home",
  "verse-pool",
  "chunk-registry.generated.ts",
);

if (!fs.existsSync(path.join(poolDir, "manifest.json"))) {
  console.error(`Missing ${poolDir}/manifest.json. Run: npm run mobile:sync-home-verse-pool`);
  process.exit(1);
}

const chunkFiles = fs
  .readdirSync(poolDir)
  .filter((n) => /^chunk-\d+\.json$/.test(n))
  .map((n) => Number(n.replace("chunk-", "").replace(".json", "")))
  .sort((a, b) => a - b);

const relPrefix = "../../../assets/content/home-prayer-pools/theme-repeat-ge5";
const lines = [
  "/** AUTO-GENERATED by scripts/generate-mobile-home-verse-chunk-registry.mjs — do not edit */",
  'import type { HomePrayerChunkV1 } from "./types";',
  "",
  "export const HOME_VERSE_POOL_SCOPE_ID = \"theme-repeat-ge5\" as const;",
  "",
  "export const HOME_VERSE_POOL_CHUNKS: Record<number, HomePrayerChunkV1> = {",
];
for (const i of chunkFiles) {
  lines.push(`  ${i}: require("${relPrefix}/chunk-${i}.json"),`);
}
lines.push("};", "");

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `${lines.join("\n")}\n`);
console.log(`Wrote ${outFile} (${chunkFiles.length} chunks)`);
