function syncMusic() {
  const store = JSON.parse(fs.readFileSync(musicPath, "utf8"));
  const tracks = Array.isArray(store.audioTracks) ? store.audioTracks : [];
  rmDirIfExists(musicTrackDir);
  rmDirIfExists(musicAnalysisDir);
  ensureDir(musicTrackDir);
  ensureDir(musicAnalysisDir);

  const trackEntries = [];
  const analysisEntries = [];
  const padEntries = [];
  let orderedTracks = tracks.filter((t) => t?.hidden !== true);

  if (androidMusicPad) {
    const split = splitTracksForAndroidPad(orderedTracks);
    orderedTracks = split.base;
    console.log(
      `Music tracks (Android PAD): ${split.base.length} album starters in base, ${split.pad.length} in fast-follow pack:`,
    );
    clearAndroidMusicPadAssets();
    ensureDir(androidMusicPadAssetsDir);
    for (const t of split.pad) {
      const id = String(t.id || "").trim();
      const srcRel = String(t.src || "").trim();
      if (!id || !srcRel) continue;
      const ext = path.extname(srcRel) || ".m4a";
      const trackFile = `${id}${ext}`;
      if (copyIfExists(srcRel, path.join(androidMusicPadAssetsDir, trackFile))) {
        padEntries.push({ id, file: trackFile });
      }
    }
    emitAndroidMusicPadManifest(padEntries);
  } else if (musicStartersOnly) {
    const split = splitTracksForAndroidPad(orderedTracks);
    orderedTracks = split.base;
    clearAndroidMusicPadAssets();
    emitAndroidMusicPadManifest([]);
    console.log(
      `Music tracks (album starters → install; ${split.pad.length} others → R2 stream/cache):`,
    );
    for (const t of split.base) {
      console.log(`  starter ${albumKeyForTrack(t)}: ${t.id}`);
    }
  } else {
    clearAndroidMusicPadAssets();
    emitAndroidMusicPadManifest([]);
    if (starterTrackId) {
      orderedTracks = [...orderedTracks].sort((a, b) => {
        const aHit = String(a.id || "").trim() === starterTrackId ? 0 : 1;
        const bHit = String(b.id || "").trim() === starterTrackId ? 0 : 1;
        return aHit - bHit;
      });
    }
    console.log(
      bundleMusicLimit === Number.POSITIVE_INFINITY
        ? "Music tracks (full bundle):"
        : `Music tracks (bundle limit=${bundleMusicLimit}, starter=${starterTrackId || "first"}):`,
    );
  }

  for (const t of orderedTracks) {
    if (!androidMusicPad && trackEntries.length >= bundleMusicLimit) break;
    const id = String(t.id || "").trim();
    const srcRel = String(t.src || "").trim();
    if (!id || !srcRel) continue;
    if (
      !androidMusicPad &&
      starterTrackId &&
      trackEntries.length === 0 &&
      bundleMusicLimit === 1 &&
      id !== starterTrackId
    ) {
      continue;
    }
    const ext = path.extname(srcRel) || ".m4a";
    const trackFile = `${id}${ext}`;
    if (copyIfExists(srcRel, path.join(musicTrackDir, trackFile))) {
      trackEntries.push({ id, file: trackFile });
    }
    const analysisRel = String(t.analysisSrc || "").trim();
    if (analysisRel) {
      const aExt = path.extname(analysisRel) || ".json";
      const analysisFile = `${id}${aExt}`;
      if (copyIfExists(analysisRel, path.join(musicAnalysisDir, analysisFile))) {
        analysisEntries.push({ id, file: analysisFile });
      }
    }
  }

  emitResolver(
    "bundled-music-tracks.ts",
    "resolveBundledMusicTrackUri",
    trackEntries,
    "../../../assets/music/tracks",
    { moduleGetter: "BundledMusicTrackModule" },
  );
  emitJsonMap(
    "bundled-music-analysis.ts",
    "getBundledMusicAnalysis",
    analysisEntries,
    "../../../assets/music/analysis",
  );
  return {
    trackCount: trackEntries.length,
    analysisCount: analysisEntries.length,
    padTrackCount: padEntries.length,
    firstTrackFile: trackEntries[0]?.file ?? null,
  };
}

