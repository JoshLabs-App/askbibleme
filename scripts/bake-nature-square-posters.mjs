#!/usr/bin/env node
/**
 * Bake 1:1 center-cropped nature posters for lock-screen / Now Playing artwork.
 *
 * Usage: node scripts/bake-nature-square-posters.mjs
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sharpDir = path.join(repoRoot, "apps/askbible-mobile/assets/nature/posters");
const squareDir = path.join(repoRoot, "apps/askbible-mobile/assets/nature/posters-square");
const generatedDir = path.join(
  repoRoot,
  "apps/askbible-mobile/src/media/generated",
);

/** Lock-screen artwork edge length (px). */
const EDGE = 1200;

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function writeGenerated(entries) {
  const imports = entries
    .map((e) => `  "${e.id}": require("../../../assets/nature/posters-square/${e.file}"),`)
    .join("\n");
  const ids = entries.map((e) => `"${e.id}"`).join(", ");
  const content = `// AUTO-GENERATED by scripts/bake-nature-square-posters.mjs — do not edit
import { Asset } from "expo-asset";

const modules = {
${imports}
} as const;

export const BUNDLED_NATURE_SQUARE_POSTER_IDS = [${ids}] as const;

export function resolveBundledNatureSquarePosterUri(id: string): string | null {
  const mod = modules[id as keyof typeof modules];
  if (mod == null) return null;
  return Asset.fromModule(mod).uri;
}

export function getBundledNatureSquarePosterModule(id: string): number | null {
  const mod = modules[id as keyof typeof modules];
  return mod ?? null;
}

export function listBundledNatureSquarePosterModules(): Array<{ id: string; module: number }> {
  return BUNDLED_NATURE_SQUARE_POSTER_IDS.map((id) => ({
    id,
    module: modules[id],
  }));
}
`;
  ensureDir(generatedDir);
  fs.writeFileSync(path.join(generatedDir, "bundled-nature-posters-square.ts"), content);
}

function main() {
  if (!fs.existsSync(sharpDir)) {
    console.error(`Missing sharp posters: ${sharpDir}`);
    process.exit(1);
  }
  ensureDir(squareDir);

  const files = fs
    .readdirSync(sharpDir)
    .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
    .sort();
  if (!files.length) {
    console.error("No poster files to bake.");
    process.exit(1);
  }

  const entries = [];
  console.log(`Baking ${files.length} square poster(s) (1:1 center crop → ${EDGE}px)…`);
  for (const file of files) {
    const id = path.basename(file, path.extname(file));
    const src = path.join(sharpDir, file);
    const outName = `${id}.jpg`;
    const out = path.join(squareDir, outName);
    // Center square crop, then downscale for lock-screen artwork size.
    execFileSync(
      "ffmpeg",
      [
        "-y",
        "-i",
        src,
        "-vf",
        `crop='min(iw,ih)':'min(iw,ih)':'(iw-min(iw,ih))/2':'(ih-min(iw,ih))/2',scale=${EDGE}:${EDGE}`,
        "-q:v",
        "3",
        out,
      ],
      { stdio: "pipe" },
    );
    const sizeKb = Math.round(fs.statSync(out).size / 1024);
    console.log(`  ✓ ${outName} (${sizeKb} KB)`);
    entries.push({ id, file: outName });
  }

  writeGenerated(entries);
  console.log(`Wrote bundled-nature-posters-square.ts (${entries.length} entries)`);
}

main();
